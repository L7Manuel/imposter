/**
 * Obtiene la palabra señuelo para el Impostor en modo "Infiltrado Engañado".
 */
export function getUndercoverWord(innocentWord: string, pool: string[]): string {
  if (UNDERCOVER_PAIRS[innocentWord]) {
    return UNDERCOVER_PAIRS[innocentWord];
  }
  const alternatives = pool.filter((w) => w !== innocentWord);
  if (alternatives.length === 0) return `${innocentWord} Especial`;
  return alternatives[Math.floor(Math.random() * alternatives.length)]!;
}

